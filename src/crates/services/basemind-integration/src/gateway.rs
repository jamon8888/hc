//! The privacy gateway capability — the product's mark on its own sidecar.
//!
//! The basemind fork (ADR-0015, PR #93) makes a workspace that carries a
//! `safe/` mirror **protected**: the two MCP tools that hand out true values —
//! `redact_text` and `vault` — are withheld from the agent surface, together
//! with the four upstream resources. They are reopened only for a basemind
//! process marked with [`GATEWAY_TOKEN_ENV`].
//!
//! OpenBitFun **is** the gateway (ADR 0001 puts the values in the product's
//! redaction store, not in the fork), so the daemon this product starts is the
//! process that must carry the marker. The value is generated by this module
//! and set only on the sidecar process through its command environment; it is
//! deliberately never placed in the host's process-wide environment, so an
//! agent sandbox cannot inherit it.
//!
//! The capability residual risk stays where basemind's ADR-0015 records it: an
//! agent able to spawn its own processes could start an unmarked basemind; the
//! guard against that is the agent runtime's OS sandbox, not this marker.

/// Environment variable the gateway sets on the basemind process it owns.
///
/// Its presence (non-empty) marks that process as the gateway's own and
/// re-opens the two withheld tools for it. The value is a random per-launch
/// secret: knowing the variable name is not the capability.
#[cfg(feature = "basemind")]
pub const GATEWAY_TOKEN_ENV: &str = "BASEMIND_GATEWAY_TOKEN";

/// The mirror directory that marks a workspace as protected.
///
/// Any `safe` entry (directory, file, symlink) inside the workspace root
/// counts — the fork's check fails closed, and this one mirrors it.
#[cfg(feature = "basemind")]
pub const MIRROR_DIR: &str = "safe";

/// Generate a random gateway token.
///
/// 32 bytes from the OS source of randomness, hex-encoded: readable in the
/// command environment without any quoting hazards, and never reused across
/// launches. Randomness failure is an error, not a panic, so a launch that
/// cannot mint a token reports and skips the daemon instead of unwinding the
/// host.
#[cfg(feature = "basemind")]
pub fn generate_gateway_token() -> Result<String, rand::Error> {
    use rand::RngCore;
    let mut bytes = [0u8; 32];
    rand::RngCore::try_fill_bytes(&mut rand::rngs::OsRng, &mut bytes)?;
    // The hex helper belongs to the basemind feature, where the other
    // random-value helpers live, so a non-basemind build has no crypto code.
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    Ok(out)
}

/// True when `root` carries a `safe/` mirror, exactly like the fork's check.
///
/// Fails closed: any present entry marks the workspace protected — including a
/// symlink, which may point at the originals rather than at a mirror — and so
/// does an entry that errors on inspection. An inspection failure is not an
/// absence: a workspace we cannot look at is precisely where under-redacting
/// the answer would hurt most.
#[cfg(feature = "basemind")]
pub fn is_protected_workspace(root: &std::path::Path) -> bool {
    match std::fs::symlink_metadata(root.join(MIRROR_DIR)) {
        Ok(_) => true,
        Err(error) => error.kind() != std::io::ErrorKind::NotFound,
    }
}

#[cfg(all(test, feature = "basemind"))]
mod tests {
    use super::*;

    /// Two tokens are two launches: the capability is not a stable flag an
    /// agent could learn once.
    #[test]
    fn tokens_are_random_and_formatted() {
        let first = generate_gateway_token().expect("mint a token");
        let second = generate_gateway_token().expect("mint a token");
        assert_ne!(first, second);
        assert_eq!(first.len(), 64);
        assert!(first.chars().all(|c| c.is_ascii_hexdigit()));
    }

    #[test]
    fn a_workspace_without_the_mirror_is_not_protected() {
        let dir = std::env::temp_dir().join(format!("obf-gateway-{}", std::process::id()));
        let root = dir.join("plain");
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&root).expect("create workspace root");
        assert!(!is_protected_workspace(&root));

        // A symlink is enough to count as a mirror: it may point at the
        // originals rather than at the redacted copy.
        #[cfg(unix)]
        {
            std::os::unix::fs::symlink(root.join("elsewhere"), root.join(MIRROR_DIR))
                .expect("create a safe symlink");
            assert!(is_protected_workspace(&root));
        }
        std::fs::remove_dir_all(&dir).ok();
    }
}
